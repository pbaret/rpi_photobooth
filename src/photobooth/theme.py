"""Typed, validated event-theme configuration for participant screens.

The event theme is persisted in a dedicated JSON document, ``theme.json``,
stored beside ``config.json``. Swapping that one file changes the visual
identity of an event (colors, background artwork, PREVIEW and REVIEW
composition) without touching startup or booth settings, templates or CSS.

The model is a closed vocabulary: colors are ``#rrggbb`` values, a background
image is an opaque identifier managed by ``BackgroundService`` and every
layout choice is an enum. Templates receive only CSS custom properties and
allowlisted class names derived in this module, so configuration can never
inject CSS declarations, HTML or JavaScript.
"""

from collections.abc import Mapping
from dataclasses import dataclass, field
from enum import Enum
from pathlib import Path
import re
from typing import TypeVar, cast

from photobooth.config import ConfigurationError, read_json_object, write_json_atomically

_HEX_COLOR_PATTERN = re.compile(r"#[0-9a-fA-F]{6}\Z")
_BACKGROUND_IDENTIFIER_PATTERN = re.compile(r"[A-Za-z0-9_-]{22}\.(?:jpg|png)\Z")

_EnumT = TypeVar("_EnumT", bound=Enum)


def is_background_identifier(value: str) -> bool:
    """Return whether ``value`` has the shape of a managed background filename.

    Identifiers are generated by ``BackgroundService``; accepting only this
    shape guarantees that a theme value can never express a path or URL.
    """
    return _BACKGROUND_IDENTIFIER_PATTERN.match(value) is not None


def theme_path_for(config_path: Path) -> Path:
    """Return the theme document location that accompanies ``config_path``."""
    return config_path.with_name("theme.json")


class BackgroundFit(str, Enum):
    """Scale an event background image to fill or fit the viewport."""

    COVER = "cover"
    CONTAIN = "contain"


class BackgroundPosition(str, Enum):
    """Anchor an event background image against the viewport."""

    CENTER = "center"
    TOP = "top"
    BOTTOM = "bottom"
    LEFT = "left"
    RIGHT = "right"
    TOP_LEFT = "top-left"
    TOP_RIGHT = "top-right"
    BOTTOM_LEFT = "bottom-left"
    BOTTOM_RIGHT = "bottom-right"

    @property
    def css_value(self) -> str:
        """Return the equivalent CSS ``background-position`` keywords."""
        return self.value.replace("-", " ")


class HeroPosition(str, Enum):
    """Place the dominant element (preview or photo) horizontally on the stage."""

    LEFT = "left"
    CENTER = "center"
    RIGHT = "right"


class HeroSize(str, Enum):
    """Select the dominant element's share of the usable stage width.

    CSS converts the share into a width that is also capped by the available
    height and the element's aspect ratio, so no size can overflow the screen.
    """

    SMALL = "small"
    MEDIUM = "medium"
    LARGE = "large"
    FULL = "full"


class PreviewFit(str, Enum):
    """Choose whether the live preview shows the whole frame or fills its area.

    ``contain`` frames the camera image at its own aspect ratio. ``cover``
    stretches the frame to the full stage height and crops the camera image.
    """

    CONTAIN = "contain"
    COVER = "cover"


class WidgetAnchor(str, Enum):
    """Semantic stage position for a secondary participant widget.

    Side anchors place the widget in the free column beside the dominant
    element; centered anchors span the stage width at its top or bottom. A
    fully centered anchor is deliberately absent because it would cover the
    camera preview or photograph.
    """

    TOP_LEFT = "top-left"
    TOP_CENTER = "top-center"
    TOP_RIGHT = "top-right"
    LEFT = "left"
    RIGHT = "right"
    BOTTOM_LEFT = "bottom-left"
    BOTTOM_CENTER = "bottom-center"
    BOTTOM_RIGHT = "bottom-right"

    @property
    def horizontal(self) -> str:
        """Return ``left``, ``center`` or ``right``."""
        return self.value.rpartition("-")[2]

    @property
    def vertical(self) -> str:
        """Return ``top``, ``middle`` or ``bottom``."""
        return self.value.rpartition("-")[0] or "middle"

    @property
    def css_classes(self) -> str:
        """Return the allowlisted classes that position a widget container."""
        return f"anchor anchor-x-{self.horizontal} anchor-y-{self.vertical}"


@dataclass(frozen=True)
class ThemeColors:
    """Hold the participant palette as validated ``#rrggbb`` strings.

    ``primary_text`` is drawn on ``primary`` (capture and main action
    buttons); ``foreground`` is drawn on ``background`` and ``surface``.
    Contrast between these pairs is the event designer's responsibility.
    """

    background: str = "#111316"
    surface: str = "#1f2328"
    foreground: str = "#f5f1e8"
    primary: str = "#f2b544"
    primary_text: str = "#15171a"

    def __post_init__(self) -> None:
        """Reject any value that is not a six-digit hexadecimal color."""
        for name, value in (
            ("background", self.background),
            ("surface", self.surface),
            ("foreground", self.foreground),
            ("primary", self.primary),
            ("primary_text", self.primary_text),
        ):
            if _HEX_COLOR_PATTERN.match(value) is None:
                raise ConfigurationError(f"colors.{name} must be a #rrggbb hex color")


@dataclass(frozen=True)
class BackgroundSettings:
    """Describe the optional event artwork behind participant screens.

    ``image`` is a managed background identifier or ``None`` for a solid
    background color. A configured image that no longer exists is ignored at
    render time and the background color is used instead.
    """

    image: str | None = None
    fit: BackgroundFit = BackgroundFit.COVER
    position: BackgroundPosition = BackgroundPosition.CENTER

    def __post_init__(self) -> None:
        """Reject identifiers that were not produced by the background store."""
        if self.image is not None and not is_background_identifier(self.image):
            raise ConfigurationError(
                "background.image must be a managed background identifier"
            )


@dataclass(frozen=True)
class PreviewLayout:
    """Compose the IDLE/COUNTDOWN booth screen.

    The title and capture button may not share an anchor, which guarantees
    that the capture button is never hidden behind another widget.
    """

    position: HeroPosition = HeroPosition.LEFT
    size: HeroSize = HeroSize.LARGE
    fit: PreviewFit = PreviewFit.CONTAIN
    capture_position: WidgetAnchor = WidgetAnchor.RIGHT
    title_visible: bool = True
    title_position: WidgetAnchor = WidgetAnchor.TOP_RIGHT

    def __post_init__(self) -> None:
        """Reject a visible title placed on top of the capture button."""
        if self.title_visible and self.title_position is self.capture_position:
            raise ConfigurationError(
                "preview.title_position must differ from preview.capture_position"
            )

    @property
    def stage_classes(self) -> str:
        """Return the allowlisted stage classes for this composition."""
        return (
            f"hero-{self.position.value} hero-size-{self.size.value} "
            f"hero-fit-{self.fit.value}"
        )


@dataclass(frozen=True)
class ReviewLayout:
    """Compose the REVIEW screen around the captured photograph.

    The QR and action panels are both tall. They may share a side column only
    when one is at the top and the other at the bottom, and a centered panel
    may not share its row with another panel; other combinations could overlap
    on a landscape phone and are rejected.
    """

    photo_position: HeroPosition = HeroPosition.LEFT
    photo_size: HeroSize = HeroSize.MEDIUM
    qr_position: WidgetAnchor = WidgetAnchor.TOP_RIGHT
    actions_position: WidgetAnchor = WidgetAnchor.BOTTOM_RIGHT

    def __post_init__(self) -> None:
        """Reject panel placements that can overlap."""
        qr = self.qr_position
        actions = self.actions_position
        same_column = qr.horizontal == actions.horizontal and (
            qr is actions or "middle" in {qr.vertical, actions.vertical}
        )
        same_row = qr.vertical == actions.vertical and "center" in {
            qr.horizontal,
            actions.horizontal,
        }
        if same_column or same_row:
            raise ConfigurationError(
                "review.actions_position overlaps review.qr_position; "
                "use opposite sides or top and bottom of the same side"
            )

    @property
    def stage_classes(self) -> str:
        """Return the allowlisted stage classes for this composition."""
        return (
            f"hero-{self.photo_position.value} hero-size-{self.photo_size.value} "
            "hero-fit-contain"
        )


@dataclass(frozen=True)
class ThemeSettings:
    """Aggregate every event-specific visual choice for participant screens.

    Instances are immutable; the admin interface replaces the application's
    current instance after a successful save. Absent theme values always fall
    back to the defaults declared on the component models.
    """

    colors: ThemeColors = field(default_factory=ThemeColors)
    background: BackgroundSettings = field(default_factory=BackgroundSettings)
    preview: PreviewLayout = field(default_factory=PreviewLayout)
    review: ReviewLayout = field(default_factory=ReviewLayout)

    def css_variables(self) -> dict[str, str]:
        """Map validated values to the participant stylesheet's custom properties.

        The background image is deliberately excluded: its URL depends on the
        request and on whether the managed file still exists.
        """
        colors = self.colors
        return {
            "--booth-background-color": colors.background,
            "--booth-surface-color": colors.surface,
            "--booth-foreground-color": colors.foreground,
            "--booth-primary-color": colors.primary,
            "--booth-primary-text-color": colors.primary_text,
            "--booth-background-fit": self.background.fit.value,
            "--booth-background-position": self.background.position.css_value,
        }


def load_theme(path: Path) -> ThemeSettings:
    """Load the event theme, using defaults when the file does not exist.

    Missing sections or keys keep their defaults. Malformed JSON, unknown keys
    and invalid values raise ``ConfigurationError`` naming the theme file.
    """
    try:
        return parse_theme(read_json_object(path))
    except ConfigurationError as error:
        raise ConfigurationError(f"invalid theme file {path.name}: {error}") from error


def save_theme(path: Path, theme: ThemeSettings) -> None:
    """Atomically persist a validated theme; ``OSError`` leaves the old file."""
    write_json_atomically(path, theme_to_document(theme))


def theme_to_document(theme: ThemeSettings) -> dict[str, object]:
    """Serialize a theme into the documented ``theme.json`` structure."""
    colors = theme.colors
    preview = theme.preview
    review = theme.review
    return {
        "colors": {
            "background": colors.background,
            "surface": colors.surface,
            "foreground": colors.foreground,
            "primary": colors.primary,
            "primary_text": colors.primary_text,
        },
        "background": {
            "image": theme.background.image,
            "fit": theme.background.fit.value,
            "position": theme.background.position.value,
        },
        "preview": {
            "position": preview.position.value,
            "size": preview.size.value,
            "fit": preview.fit.value,
            "capture_position": preview.capture_position.value,
            "title_visible": preview.title_visible,
            "title_position": preview.title_position.value,
        },
        "review": {
            "photo_position": review.photo_position.value,
            "photo_size": review.photo_size.value,
            "qr_position": review.qr_position.value,
            "actions_position": review.actions_position.value,
        },
    }


def parse_theme(document: Mapping[str, object]) -> ThemeSettings:
    """Validate an external theme document and build the typed model.

    Used for both ``theme.json`` and admin submissions. Error messages start
    with the dotted setting path, e.g. ``colors.primary``.
    """
    _reject_unknown_keys(document, {"colors", "background", "preview", "review"}, "theme")
    defaults = ThemeSettings()
    colors = _section(
        document, "colors", {"background", "surface", "foreground", "primary", "primary_text"}
    )
    background = _section(document, "background", {"image", "fit", "position"})
    preview = _section(
        document,
        "preview",
        {"position", "size", "fit", "capture_position", "title_visible", "title_position"},
    )
    review = _section(
        document,
        "review",
        {"photo_position", "photo_size", "qr_position", "actions_position"},
    )
    return ThemeSettings(
        colors=ThemeColors(
            background=_string(colors, "colors", "background", defaults.colors.background),
            surface=_string(colors, "colors", "surface", defaults.colors.surface),
            foreground=_string(colors, "colors", "foreground", defaults.colors.foreground),
            primary=_string(colors, "colors", "primary", defaults.colors.primary),
            primary_text=_string(
                colors, "colors", "primary_text", defaults.colors.primary_text
            ),
        ),
        background=BackgroundSettings(
            image=_optional_identifier(background),
            fit=_enum(background, "background", "fit", defaults.background.fit),
            position=_enum(
                background, "background", "position", defaults.background.position
            ),
        ),
        preview=PreviewLayout(
            position=_enum(preview, "preview", "position", defaults.preview.position),
            size=_enum(preview, "preview", "size", defaults.preview.size),
            fit=_enum(preview, "preview", "fit", defaults.preview.fit),
            capture_position=_enum(
                preview, "preview", "capture_position", defaults.preview.capture_position
            ),
            title_visible=_boolean(
                preview, "preview", "title_visible", defaults.preview.title_visible
            ),
            title_position=_enum(
                preview, "preview", "title_position", defaults.preview.title_position
            ),
        ),
        review=ReviewLayout(
            photo_position=_enum(
                review, "review", "photo_position", defaults.review.photo_position
            ),
            photo_size=_enum(review, "review", "photo_size", defaults.review.photo_size),
            qr_position=_enum(review, "review", "qr_position", defaults.review.qr_position),
            actions_position=_enum(
                review, "review", "actions_position", defaults.review.actions_position
            ),
        ),
    )


def _reject_unknown_keys(
    values: Mapping[str, object], supported: set[str], section: str
) -> None:
    """Raise for the first unsupported key so typos are not silently ignored."""
    unknown = values.keys() - supported
    if unknown:
        raise ConfigurationError(f"unknown {section} setting: {sorted(unknown)[0]}")


def _section(
    document: Mapping[str, object], name: str, supported: set[str]
) -> dict[str, object]:
    """Return one validated object section, or an empty one when absent."""
    raw = document.get(name, {})
    if not isinstance(raw, dict):
        raise ConfigurationError(f"{name} must be an object")
    section = cast(dict[object, object], raw)
    values: dict[str, object] = {}
    for key, value in section.items():
        if not isinstance(key, str):
            raise ConfigurationError(f"{name} keys must be strings")
        values[key] = value
    _reject_unknown_keys(values, supported, name)
    return values


def _string(values: Mapping[str, object], section: str, name: str, default: str) -> str:
    """Return a string setting or raise a path-prefixed type error."""
    value = values.get(name, default)
    if not isinstance(value, str):
        raise ConfigurationError(f"{section}.{name} must be a string")
    return value


def _boolean(values: Mapping[str, object], section: str, name: str, default: bool) -> bool:
    """Return a JSON boolean setting or raise a path-prefixed type error."""
    value = values.get(name, default)
    if not isinstance(value, bool):
        raise ConfigurationError(f"{section}.{name} must be a boolean")
    return value


def _optional_identifier(values: Mapping[str, object]) -> str | None:
    """Return the background identifier, treating null and blank as no image."""
    value = values.get("image")
    if value is None or value == "":
        return None
    if not isinstance(value, str):
        raise ConfigurationError("background.image must be a string or null")
    return value


def _enum(
    values: Mapping[str, object], section: str, name: str, default: _EnumT
) -> _EnumT:
    """Return the member of ``default``'s enum whose value matches the setting."""
    raw = values.get(name, default.value)
    enum_type = type(default)
    for member in enum_type:
        if member.value == raw:
            return member
    allowed = ", ".join(str(member.value) for member in enum_type)
    raise ConfigurationError(f"{section}.{name} must be one of: {allowed}")
